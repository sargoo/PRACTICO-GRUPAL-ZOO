public enum Tipo_Pelaje {
    PELOS_DE_GUARDIA ("pelos largos y gruesos de la capa externa"),
    SUBPELO ("capa interna formada por pelos más cortos"),
    VIBRISAS("bigotes o pelos táctiles");

    private String Descripcion;

    Tipo_Pelaje(String descripcion) {
        Descripcion = descripcion;
    }
}
